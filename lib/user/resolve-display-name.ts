type UserMetadata = {
  full_name?: string;
  name?: string;
  display_name?: string;
};

const LEGACY_GENERIC_DISPLAY_NAME = "Học viên";
const AUTO_DISPLAY_NAME_PATTERN = /^user\d+$/;

export function pickTrimmedName(value: unknown): string {
  if (typeof value !== "string") {
    return "";
  }

  return value.trim();
}

export function resolveAuthMetadataDisplayName(
  userMetadata: UserMetadata | undefined,
): string {
  return (
    pickTrimmedName(userMetadata?.full_name) ||
    pickTrimmedName(userMetadata?.name) ||
    pickTrimmedName(userMetadata?.display_name)
  );
}

export function createFallbackDisplayName(): string {
  return `user${Date.now()}`;
}

export function isAutoGeneratedDisplayName(
  displayName: string | null | undefined,
): boolean {
  const current = pickTrimmedName(displayName);
  return current.length > 0 && AUTO_DISPLAY_NAME_PATTERN.test(current);
}

export function shouldSyncProfileDisplayName(
  currentDisplayName: string | null | undefined,
  email: string | undefined,
): boolean {
  const current = pickTrimmedName(currentDisplayName);
  if (!current) {
    return true;
  }

  if (current === LEGACY_GENERIC_DISPLAY_NAME || isAutoGeneratedDisplayName(current)) {
    return true;
  }

  if (!email) {
    return false;
  }

  const emailTrimmed = email.trim();
  const localPart = emailTrimmed.split("@")[0] ?? "";

  return current === emailTrimmed || (localPart.length > 0 && current === localPart);
}

export function resolveUserDisplayName(
  profileDisplayName: string | null | undefined,
  userMetadata: UserMetadata | undefined,
): string {
  const fromProfile = pickTrimmedName(profileDisplayName);
  if (fromProfile) {
    return fromProfile;
  }

  const fromMetadata = resolveAuthMetadataDisplayName(userMetadata);
  if (fromMetadata) {
    return fromMetadata;
  }

  return createFallbackDisplayName();
}

export async function fetchUserDisplayName(
  supabase: Awaited<
    ReturnType<typeof import("@/lib/supabase/server").createClient>
  >,
  userId: string,
  userMetadata: UserMetadata | undefined,
): Promise<string> {
  const { data: profile } = await supabase
    .from("profiles")
    .select("display_name")
    .eq("id", userId)
    .maybeSingle();

  const profileName = pickTrimmedName(profile?.display_name);
  const metadataName = resolveAuthMetadataDisplayName(userMetadata);

  if (profileName) {
    return profileName;
  }

  if (metadataName) {
    return metadataName;
  }

  const fallback = createFallbackDisplayName();
  await supabase
    .from("profiles")
    .update({ display_name: fallback })
    .eq("id", userId);

  return fallback;
}
